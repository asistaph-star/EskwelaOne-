import { PrismaClient } from '@prisma/client';

const prisma = new PrismaClient();

// Hard-block execution in production
if (process.env.NODE_ENV === 'production') {
  console.error('FATAL: Running fixture scripts in production is strictly prohibited.');
  process.exit(1);
}

export async function cleanupFixture(): Promise<void> {
  console.log('[FIXTURE CLEANUP] Starting cleanup of synthetic fixture records...');

  // 1. Delete Grade Entries (depends on columns & enrollments)
  const gradeEntryRes = await prisma.grade_entries.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { column_id: { startsWith: 'fix-' } },
        { enrollment_id: { startsWith: 'fix-' } }
      ]
    }
  });

  // 2. Delete Gradebook Columns (depends on gradebooks)
  const gradeColRes = await prisma.gradebook_columns.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { gradebook_id: { startsWith: 'fix-' } },
        { gradebook: { assignment_id: { startsWith: 'fix-' } } }
      ]
    }
  });

  // 3. Delete Gradebooks
  const gradebookRes = await prisma.gradebooks.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { assignment_id: { startsWith: 'fix-' } }
      ]
    }
  });

  // 4. Delete Class Attendance
  const classAttRes = await prisma.classAttendance.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { enrollment_id: { startsWith: 'fix-' } },
        { assignment_id: { startsWith: 'fix-' } }
      ]
    }
  });

  // 5. Delete Appointments
  const apptRes = await prisma.appointment.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 6. Delete Excuse Letters
  const excuseRes = await prisma.excuseLetter.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 7. Delete Gate Attendance
  const gateRes = await prisma.gateAttendance.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 8. Delete Grades (official term grades)
  const gradeRes = await prisma.grade.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 9. Delete Enrollments
  const enrollRes = await prisma.enrollment.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { section_id: { startsWith: 'fix-' } }
      ]
    }
  });

  // 10. Delete Teacher Subject Assignments for fixture
  const assignmentRes = await prisma.teacherSubjectAssignment.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { section_id: { startsWith: 'fix-' } }
      ]
    }
  });

  // 11. Delete Students
  const studentRes = await prisma.student.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 12. Delete UserRoles for fixture users
  const userRoleRes = await prisma.userRole.deleteMany({
    where: { user_id: { startsWith: 'fix-' } }
  });

  // 13. Delete AuditLogs generated by tests on fixture users
  const auditRes = await prisma.auditLog.deleteMany({
    where: { actor_user_id: { startsWith: 'fix-' } }
  });

  // 14. Delete Users
  const userRes = await prisma.user.deleteMany({
    where: {
      OR: [
        { id: { startsWith: 'fix-' } },
        { email: { endsWith: '@fixture.invalid' } }
      ]
    }
  });

  // 15. Delete Sections for fixture
  const sectionRes = await prisma.section.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  // 16. Delete Subjects for fixture (if any)
  const subjectRes = await prisma.subject.deleteMany({
    where: { id: { startsWith: 'fix-' } }
  });

  console.log('[FIXTURE CLEANUP COMPLETED]');
  console.log({
    deletedGradeEntries: gradeEntryRes.count,
    deletedGradebookColumns: gradeColRes.count,
    deletedGradebooks: gradebookRes.count,
    deletedClassAttendance: classAttRes.count,
    deletedAppointments: apptRes.count,
    deletedExcuseLetters: excuseRes.count,
    deletedGateAttendance: gateRes.count,
    deletedGrades: gradeRes.count,
    deletedEnrollments: enrollRes.count,
    deletedAssignments: assignmentRes.count,
    deletedSections: sectionRes.count,
    deletedSubjects: subjectRes.count,
    deletedStudents: studentRes.count,
    deletedUserRoles: userRoleRes.count,
    deletedAuditLogs: auditRes.count,
    deletedUsers: userRes.count,
  });
}

// Direct invocation check
if (process.argv[1]?.endsWith('cleanup-teacher-demo-fixture.ts')) {
  cleanupFixture()
    .catch((err) => {
      console.error('[FIXTURE CLEANUP FAILED]', err);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}
