/**
 * DigiSkwela Roles & Permissions Service
 * 
 * Production-grade metadata service representing Calulut Integrated National High School's
 * actual backend RBAC implementation.
 * 
 * ABSOLUTE ACCURACY RULES:
 * 1. Every role corresponds to an actual system role in PostgreSQL (Role model).
 * 2. Every capability maps to actual backend route enforcement (requirePermissions,
 *    requireAnyPermission, or route-level role/ownership checks).
 * 3. Contextual constraints (e.g. assigned section only, own records only) are explicitly
 *    differentiated from global access (ALLOWED vs CONDITIONAL vs DENIED).
 * 4. Disparities between ITAdmin and Admin (e.g. School Customization mutations, Inventory Void,
 *    Security Audit logs) are precisely represented.
 */

export type AccessLevel = 'ALLOWED' | 'DENIED' | 'CONDITIONAL';

export interface RoleAccessEntry {
  access: AccessLevel;
  condition?: string;
}

export interface CapabilityItem {
  id: string;
  name: string;
  description: string;
  action: 'READ' | 'CREATE' | 'UPDATE' | 'DELETE' | 'APPROVE' | 'EXPORT' | 'MANAGE' | 'SPECIAL';
  requiredPermission?: string;
  roleAccess: Record<string, RoleAccessEntry>;
}

export interface ModuleGroup {
  id: string;
  name: string;
  description: string;
  capabilities: CapabilityItem[];
}

export interface RoleDefinition {
  id: string;
  name: string;
  description: string;
  isAdministrative: boolean;
}

