/**
 * Retrieve the full Roles & Permissions Matrix.
 * 
 * @param isITAdmin Whether the requesting user holds the ITAdmin role.
 * Both ITAdmin and Admin can inspect the matrix; ITAdmin sees full technical notes
 * and administrative policy distinction flags.
 */
export function getRolesPermissionsMatrix(isITAdmin: boolean) {
  let totalCapabilities = 0;
  for (const moduleGroup of MODULE_GROUPS) {
    totalCapabilities += moduleGroup.capabilities.length;
  }

  return {
    meta: {
      generatedAt: new Date().toISOString(),
      viewerRole: isITAdmin ? 'ITAdmin' : 'Admin',
      totalRoles: SYSTEM_ROLES.length,
      totalModules: MODULE_GROUPS.length,
      totalCapabilities,
    },
    roles: SYSTEM_ROLES,
    modules: MODULE_GROUPS,
  };
}
